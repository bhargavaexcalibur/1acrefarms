#!/usr/bin/env python3
"""The website checkout, as far as the static site goes. Run through the whole-site build only:
    python3 tools/build_pages.py

Two jobs, both driven by build_pages.CHECKOUT_LIVE (the ONE switch) and checkout-worker/src/catalogue.json (the ONE
list of packs, prices and what can be ordered here):

1. build(): writes /checkout/, the real checkout page, from the hidden test page checkout-test/ (index.html,
   checkout.js, checkout.css, cart.js; edit those, never the copies):
     /checkout/index.html          noindex and not in sitemap.xml while CHECKOUT_LIVE = False; linked from nowhere then
     /checkout/checkout.js, cart.js imports pointed at ./lib/
     /checkout/lib/*.js            the PURE shared modules of the Worker (prices, form rules, GST, seller, cart, delivery
                                   dates) and catalogue.js (generated from catalogue.json). Never server-only code or
                                   config: the build stops if a copied module imports anything else.
     /checkout/i18n/<lang>.json    the page's strings: checkout-test/strings.en.json + seller.js TERMS in English, with
                                   each translation that passed build_i18n.problem() (keys co.<key>, all OPTIONAL);
                                   untranslated keys stay English and are listed in "en" (the page marks them lang="en").
2. hand_written(): the hand-written files follow the switch through marked blocks, and with CHECKOUT_LIVE = False they
   are put back byte for byte (the live site does not change at all while the switch is off):
     app.js       CHECKOUT:START(sellable) / (buttons): packs sold here count as shown, and their home cards get
                  "Add to cart" + "Buy now" under the Amazon.in button
     styles.css   /* CHECKOUT:START */ block at the end: cart link, buttons, free-delivery line
     index.html   <!--CART-->...<!--/CART--> after the language menu: the header cart link
     policies.html the "Directly from us" bullet of How to order: "opening soon" (off) or open (on)
"""
import html
import json
import re
import sys

sys.dont_write_bytecode = True
import build_pages as bp  # noqa: E402

ROOT = bp.ROOT
SRC_PAGE = ROOT / "checkout-test"
SRC_LIB = ROOT / "checkout-worker" / "src"
OUT = ROOT / "checkout"
# The Worker modules the page may use: pure functions and public facts only (no fetch, no secrets, no storage).
LIB_MODULES = ("pricing.js", "validate.js", "gst.js", "seller.js", "cart-link.js", "delivery.js")
JSON_IMPORT = 'import CATALOGUE_DATA from "./catalogue.json" with { type: "json" };'
JS_IMPORT = 'import CATALOGUE_DATA from "./catalogue.js";'
GEN = "GENERATED by tools/build_pages.py from {src}: edit that file and run the build, never this copy."


def fail(msg):
    sys.exit(f"build_checkout: {msg}")


# ---------------------------------------------------------------------------------------------------------------------
# Strings
# ---------------------------------------------------------------------------------------------------------------------
STRINGS_JSON = SRC_PAGE / "strings.en.json"
# Page keys whose English is TERMS in checkout-worker/src/seller.js (the order e-mail says the same).
TERM_KEYS = {
    "privacyNote": ("privacy", "note under the address form: why we ask for these details and who gets them; {link} = "
                               "the words 'privacy policy' as a link"),
    "deliveryNote": ("delivery", "delivery terms shown before the Pay button; keep every number"),
    "returnsNote": ("returns", "cancellation, returns and refunds terms shown before the Pay button; keep every number"),
    "grievanceNote": ("grievance", "how we handle a complaint (Indian consumer law); keep 48, 1AF-C-0001 and every number"),
}


def strings_en():
    """{co.<key>: (english, note)}: every visible string of the checkout page (build_i18n makes them OPTIONAL keys)."""
    doc = json.loads(STRINGS_JSON.read_text(encoding="utf-8"))
    out = {}
    for k, v in doc["strings"].items():
        if not re.fullmatch(r"[A-Za-z][\w.]*", k) or not isinstance(v.get("en"), str) or not v["en"].strip():
            fail(f"checkout-test/strings.en.json: bad entry {k!r}")
        out[f"co.{k}"] = (v["en"], "checkout page: " + v.get("note", ""))
    terms = bp.seller_terms()
    for key, (term, note) in TERM_KEYS.items():
        if f"co.{key}" in out:
            fail(f"checkout-test/strings.en.json must not hold {key}: its English is TERMS.{term} in seller.js")
        out[f"co.{key}"] = (terms[term], "checkout page: " + note)
    return out


def pack_name_sources():
    """{pack.<CODE>.name: (english, note)} for the packs the checkout can list (already translated for the pack pages)."""
    return {f"pack.{p['code']}.name": (f"{p['name']} ({p['local']})", "") for p in bp.PACKS if p["code"] in bp.CATALOGUE}


def strings_files():
    """[(lang, data)] for /checkout/i18n/<lang>.json: English first, then every language of the site."""
    import build_i18n as bi
    src = strings_en()
    en_t = {k[3:]: text for k, (text, _) in src.items()}
    out = [("en", {"lang": "en", "dir": "ltr", "home": "/", "en": [], "t": en_t, "packs": {}, "pages": []})]
    sub = {**src, **pack_name_sources()}
    by_code = {p["code"]: p for p in bp.PACKS}
    for code, L in bi.LANG.items():
        ok, _ = bi.usable(code, sub)
        t, fallback = {}, []
        for k, (text, _) in src.items():
            t[k[3:]] = ok.get(k, text)
            if k not in ok:
                fallback.append(k[3:])
        packs = {c: ok[f"pack.{c}.name"] for c in bp.CATALOGUE if f"pack.{c}.name" in ok}
        pages = [c for c in bp.CATALOGUE if c in by_code and (ROOT / code / by_code[c]["slug"] / "index.html").exists()]
        home = f"/{code}/" if (ROOT / code / "index.html").exists() else "/"
        out.append((code, {"lang": code, "dir": L["dir"], "home": home, "en": fallback, "t": t, "packs": packs,
                           "pages": pages}))
    return out


# ---------------------------------------------------------------------------------------------------------------------
# /checkout/
# ---------------------------------------------------------------------------------------------------------------------
TEST_COMMENT = re.compile(r"  <!-- HIDDEN TEST PAGE:.*?-->\n", re.S)
ROBOTS = '  <meta name="robots" content="noindex, nofollow, noarchive" />\n'


def page_html(live):
    src = (SRC_PAGE / "index.html").read_text(encoding="utf-8")
    if len(TEST_COMMENT.findall(src)) != 1:
        fail("checkout-test/index.html: the HIDDEN TEST PAGE comment is missing")
    note = ("" if live else " Hidden while CHECKOUT_LIVE = False: noindex, not in sitemap.xml, linked from nowhere.")
    src = TEST_COMMENT.sub(lambda m: f"  <!-- {GEN.format(src='checkout-test/index.html')}{note} -->\n", src, count=1)
    reps = [('<meta name="checkout-page" content="test" />', '<meta name="checkout-page" content="prod" />'),
            ("<title>Checkout (test) · 1acrefarms</title>", "<title>Checkout · 1acrefarms</title>")]
    if live:  # open for orders: indexable, with its canonical address
        reps.append((ROBOTS, f'  <link rel="canonical" href="{bp.SITE}{bp.CHECKOUT_PATH}" />\n'))
    for a, b in reps:
        if src.count(a) != 1:
            fail(f"checkout-test/index.html: expected {a.strip()!r} exactly once")
        src = src.replace(a, b)
    if live == ("noindex" in src):
        fail("checkout/index.html: robots line does not follow CHECKOUT_LIVE")
    return src


def page_js(name):
    """checkout-test/<name> with its Worker imports pointed at ./lib/ (and only at the pure modules)."""
    src = (SRC_PAGE / name).read_text(encoding="utf-8")
    for path in re.findall(r'^import [^;]*? from "([^"]+)";', src, re.M):
        if not path.startswith("../checkout-worker/src/") or path.rsplit("/", 1)[1] not in LIB_MODULES:
            fail(f"checkout-test/{name} imports {path}: only {', '.join(LIB_MODULES)} may be served")
    return f"// {GEN.format(src='checkout-test/' + name)}\n" + src.replace('"../checkout-worker/src/', '"./lib/')


def lib_js(name):
    src = (SRC_LIB / name).read_text(encoding="utf-8")
    for path in re.findall(r'^import [^;]*? from "([^"]+)"', src, re.M):
        if not path.startswith("./") or path[2:] not in (*LIB_MODULES, "catalogue.json"):
            fail(f"checkout-worker/src/{name} imports {path}: a module served to browsers may import only "
                 f"{', '.join(LIB_MODULES)} and catalogue.json")
    if re.search(r"\benv\.|\bfetch\(|\bcrypto\.subtle|\bimport\(", src):
        fail(f"checkout-worker/src/{name} uses env / fetch / crypto / dynamic import: it is not a pure module any more")
    if name == "pricing.js":
        if src.count(JSON_IMPORT) != 1:
            fail(f"checkout-worker/src/pricing.js: expected the line {JSON_IMPORT!r} once")
        src = src.replace(JSON_IMPORT, JS_IMPORT)
    return f"// {GEN.format(src='checkout-worker/src/' + name)}\n" + src


def build(live=None):
    """Write /checkout/ (and remove anything else in it)."""
    is_live = bp.CHECKOUT_LIVE
    doc = json.loads(bp.CATALOGUE_JSON.read_text(encoding="utf-8"))
    files = {
        "index.html": page_html(is_live),
        "checkout.js": page_js("checkout.js"),
        "cart.js": page_js("cart.js"),
        "checkout.css": f"/* {GEN.format(src='checkout-test/checkout.css')} */\n"
                        + (SRC_PAGE / "checkout.css").read_text(encoding="utf-8"),
        "lib/catalogue.js": f"// {GEN.format(src='checkout-worker/src/catalogue.json')}\n"
                            f"export default {json.dumps(doc, ensure_ascii=False, indent=1)};\n",
    }
    for name in LIB_MODULES:
        files[f"lib/{name}"] = lib_js(name)
    for code, data in strings_files():
        for v in data["t"].values():
            if bp.BANNED.search(v) and code == "en":
                fail(f"banned claim word in the checkout strings: {bp.BANNED.search(v).group(0)!r}")
        files[f"i18n/{code}.json"] = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
    written = 0
    for rel, text in files.items():
        f = OUT / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            f.write_text(text, encoding="utf-8")
            written += 1
    for f in sorted(OUT.rglob("*"), reverse=True):
        rel = f.relative_to(OUT).as_posix()
        if f.is_file() and rel not in files:
            f.unlink()
        elif f.is_dir() and not any(f.iterdir()):
            f.rmdir()
    sold = [c for c, r in bp.CATALOGUE.items() if r["sellable"]]
    print(f"checkout/: {len(files)} files ({written} changed), {'LIVE' if is_live else 'hidden (CHECKOUT_LIVE = False)'}; "
          f"sellable here: {', '.join(sold) or 'none'}")


# ---------------------------------------------------------------------------------------------------------------------
# Hand-written files: marked blocks that follow CHECKOUT_LIVE (all removed, byte for byte, when it is False)
# ---------------------------------------------------------------------------------------------------------------------
APP_SELLABLE_OFF = "const sellable = (p) => p.live && !p.soon && onAmazonNow(p);"
APP_SELLABLE_RE = re.compile(r"// CHECKOUT:START\(sellable\).*?// CHECKOUT:END\(sellable\)", re.S)
APP_RENDER = "\nrenderChipNav();\nrenderCatalog();\n"
APP_BUTTONS_RE = re.compile(r"// CHECKOUT:START\(buttons\).*?// CHECKOUT:END\(buttons\)\n", re.S)


def app_sellable_on(codes):
    return ("// CHECKOUT:START(sellable) written by tools/build_pages.py while CHECKOUT_LIVE = True; with False the build puts\n"
            "// back the Amazon-only line. DIRECT = the packs sold on this website (\"sellable\" in checkout-worker/src/catalogue.json).\n"
            f"const DIRECT = {json.dumps(codes)};\n"
            "const sellable = (p) => p.live && !p.soon && (onAmazonNow(p) || DIRECT.includes(p.code));\n"
            "// CHECKOUT:END(sellable)")


def app_buttons_on():
    lab = {k: html.escape(v, quote=True) for k, v in bp.DIRECT_LABELS.items()}
    if any(c in v for v in lab.values() for c in "`$\\"):
        fail("DIRECT_LABELS cannot hold ` $ or \\ (they go into a JavaScript template)")
    return ("// CHECKOUT:START(buttons) written by tools/build_pages.py while CHECKOUT_LIVE = True (removed when False):\n"
            "// \"Add to cart\" and \"Buy now\" under the Amazon.in button of each pack sold here; /checkout/cart.js does the adding.\n"
            "const directButtons = (p) => `<div class=\"card-direct\">"
            f"<a class=\"add-btn add-cart\" href=\"/checkout/?add=${{p.code}}\" rel=\"nofollow\" data-cart-add=\"${{p.code}}\" "
            f"data-added=\"{lab['cart_added']}\" data-full=\"{lab['cart_full']}\">{lab['add_to_cart']}</a>"
            f"<a class=\"add-btn\" href=\"/checkout/?buy=${{p.code}}\" rel=\"nofollow\">{lab['buy_now']}</a></div>`;\n"
            "packCard = ((amazonCard) => (p) => {\n"
            "  const card = amazonCard(p);\n"
            "  if (!DIRECT.includes(p.code) || p.soon) return card;\n"
            "  return card.replace(new RegExp(`(id=\"order-${p.id}\">[\\\\s\\\\S]*?)(</div>)`), (m, foot, end) => foot + directButtons(p) + end);\n"
            "})(packCard);\n"
            "// CHECKOUT:END(buttons)\n")


def app_js(src, live):
    src = APP_SELLABLE_RE.sub(lambda m: APP_SELLABLE_OFF, src)
    src = APP_BUTTONS_RE.sub("", src)
    if src.count(APP_SELLABLE_OFF) != 1 or src.count(APP_RENDER) != 1:
        fail("app.js: the sellable line or the renderChipNav(); renderCatalog(); lines were not found exactly once")
    if live:
        codes = [c for c, r in bp.CATALOGUE.items() if r["sellable"]]
        src = src.replace(APP_SELLABLE_OFF, app_sellable_on(codes))
        src = src.replace(APP_RENDER, "\n" + app_buttons_on() + APP_RENDER[1:])
    return src


