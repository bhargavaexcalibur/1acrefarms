def policies_html(src, live):
    found = POLICIES_RE.findall(src)
    if len(found) != 1:
        fail(f"policies.html: expected one 'Directly from us' bullet under How to order, found {len(found)}")
    cur = found[0]
    if live:
        new = POLICIES_ON
    else:  # leave the policies session's own "opening soon" wording alone; only undo the open wording
        new = cur if "(opening soon)" in cur else POLICIES_OFF
    return src.replace(cur, new, 1)


def hand_written():
    live = bp.CHECKOUT_LIVE
    for chunk in (POLICIES_ON,):
        if bp.BANNED.search(bp.text_of(chunk)):
            fail(f"banned claim word in the open policies wording: {bp.BANNED.search(bp.text_of(chunk)).group(0)!r}")
    changed = []
    for name, fn in (("app.js", app_js), ("styles.css", styles_css), ("index.html", index_html), ("policies.html", policies_html)):
        f = ROOT / name
        old = f.read_text(encoding="utf-8")
        new = fn(old, live)
        if new != old:
            f.write_text(new, encoding="utf-8")
            changed.append(name)
    print(f"direct orders {'ON' if live else 'off'} (CHECKOUT_LIVE = {live}); hand-written files changed: {', '.join(changed) or 'none'}")
